SECRETS_FILE = Path.home() / ".openclaw" / "fleetmind-secrets.json"


def _load_secrets() -> dict:
    if SECRETS_FILE.exists():
        return json.loads(SECRETS_FILE.read_text())
    return {}


def _save_secrets(secrets: dict) -> None:
    SECRETS_FILE.parent.mkdir(parents=True, exist_ok=True)
    SECRETS_FILE.write_text(json.dumps(secrets, indent=2))
    SECRETS_FILE.chmod(0o600)


def _load_fleet(config: Path) -> "FleetConfig":  # noqa: F821
    from ..coordinator.config import FleetConfig
    if not config.exists():
        console.print(f"[red]Error:[/red] {config} not found.")
        raise typer.Exit(1)
    try:
        return FleetConfig.load(config)
    except Exception as e:
        console.print(f"[red]Error loading fleet.yaml:[/red] {e}")
        raise typer.Exit(1)


# ── Commands ──────────────────────────────────────────────────────────────────

@app.command()
def init(
    name: str = typer.Option("my-fleet", "--name", "-n", help="Fleet name"),
    client: str = typer.Option("", "--client", "-c", help="Client name"),
    output: Path = typer.Option(Path("fleet.yaml"), "--output", "-o", help="Output file"),
):
    """Scaffold a new fleet.yaml in the current directory."""
    if output.exists():
        overwrite = typer.confirm(f"{output} already exists. Overwrite?", default=False)
        if not overwrite:
            raise typer.Exit(0)

    content = FLEET_YAML_TEMPLATE.format(name=name, client=client or name)
    output.write_text(content)

    # Create rendered dir and .gitignore entry
    Path("rendered").mkdir(exist_ok=True)
    gitignore = Path(".gitignore")
    ignore_lines = ["fleet.yaml", "rendered/openclaw.json", ".env"]
    if gitignore.exists():
        existing = gitignore.read_text()
        missing = [l for l in ignore_lines if l not in existing]
        if missing:
            gitignore.write_text(existing + "\n" + "\n".join(missing) + "\n")
    else:
        gitignore.write_text("\n".join(ignore_lines) + "\n")

    console.print(f"[green]✓[/green] Created [bold]{output}[/bold]")
    console.print("\nNext steps:")
    console.print("  1. Edit fleet.yaml — add agents, Slack tokens, skills")
    console.print("  2. [bold]fleetmind secrets set CONDUCTOR_BOT_TOKEN xoxb-...[/bold]")
    console.print("  3. [bold]fleetmind deploy[/bold]")


@app.command()
def deploy(
    config: Path = typer.Argument(Path("fleet.yaml"), help="Path to fleet.yaml"),
    dry_run: bool = typer.Option(False, "--dry-run", help="Show what would happen without doing it"),
    no_render: bool = typer.Option(False, "--no-render", help="Skip rendering openclaw.json"),
    no_restart: bool = typer.Option(False, "--no-restart", help="Skip gateway restart"),
):
    """Provision agent workspaces and render openclaw.json."""
    from ..runtime.provisioner import provision_fleet
    from ..runtime.renderer import write_outputs

    fleet = _load_fleet(config)

    if dry_run:
        console.print("[yellow]Dry run — no changes will be made.[/yellow]\n")

    provision_fleet(fleet, dry_run=dry_run)

    if not no_render:
        written = write_outputs(fleet)
        for name, path in written.items():
            console.print(f"[green]✓[/green] Rendered [bold]{name}[/bold] → {path}")

    if not no_restart and not dry_run:
        console.print("\n[dim]Tip: run [bold]openclaw gateway restart[/bold] to apply the new config.[/dim]")


@app.command()
def diff(
    config: Path = typer.Argument(Path("fleet.yaml"), help="Path to fleet.yaml"),
):
    """Show what deploy would change without applying anything."""
    from ..runtime.provisioner import diff_fleet

    fleet = _load_fleet(config)
    changes = diff_fleet(fleet)

    if changes == ["No changes detected."]:
        console.print("[green]✓ No changes detected.[/green]")
    else:
        console.print(f"[bold]Changes ({len(changes)}):[/bold]")
        for change in changes:
            if change.startswith("[+]"):
                console.print(f"  [green]{change}[/green]")
            elif change.startswith("[~]"):
                console.print(f"  [yellow]{change}[/yellow]")
            elif change.startswith("[-]"):
                console.print(f"  [red]{change}[/red]")
            else:
                console.print(f"  {change}")


@app.command()
def render(
    config: Path = typer.Argument(Path("fleet.yaml"), help="Path to fleet.yaml"),
    out: Path = typer.Option(Path("."), "--out", "-o", help="Output base directory"),
):
    """Render openclaw.json and terraform vars without deploying."""
    from ..runtime.renderer import write_outputs

    fleet = _load_fleet(config)
    written = write_outputs(fleet, base_dir=out)

    console.print(f"[bold]Rendered outputs for fleet [cyan]{fleet.name}[/cyan]:[/bold]")
    for name, path in written.items():
        console.print(f"  [green]✓[/green] {name}: [dim]{path}[/dim]")


@app.command()
def watch(
    config: Path = typer.Argument(Path("fleet.yaml"), help="Path to fleet.yaml"),
    interval: Optional[str] = typer.Option(None, "--interval", help="Poll interval (e.g. 30s, 5m)"),
):
    """GitOps watcher — auto-push skill updates from the skills repo."""
    from ..runtime.watcher import SkillsWatcher

    fleet = _load_fleet(config)
    if interval:
        fleet.skills_repo.poll_interval = interval

    watcher = SkillsWatcher(fleet)
    watcher.watch()


@app.command()
def status(
    config: Path = typer.Argument(Path("fleet.yaml"), help="Path to fleet.yaml"),
):
    """Show fleet configuration and workspace status."""
    fleet = _load_fleet(config)

    console.print(Panel(
        f"[bold]{fleet.name}[/bold] v{fleet.version}\n"
        f"Client: {fleet.client}\n"
        f"{fleet.description}",
        title="Fleet Status",
    ))

    table = Table(show_header=True, header_style="bold cyan")
    table.add_column("Agent")
    table.add_column("Role")
    table.add_column("Skills")
    table.add_column("Workspace")

    for agent in fleet.agents:
        workspace = Path(fleet.defaults.workspace_base) / f"workspace-{agent.id}"
        ws_status = "[green]✓[/green]" if workspace.exists() else "[red]✗[/red]"
        role = "[magenta]orchestrator[/magenta]" if agent.orchestrator else "specialist"
        skills = ", ".join(
            f"{s.name}{'@' + s.version if s.version else ''}"
            for s in agent.skills
        ) or "—"
        table.add_row(
            f"{agent.emoji} {agent.name}",
            role,
            skills,
            f"{ws_status} {workspace}",
        )

    console.print(table)


