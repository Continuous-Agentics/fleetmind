@push_app.command("skill")
def push_skill(
    skill_name: str = typer.Argument(..., help="Skill name to push"),
    config: Path = typer.Option(Path("fleet.yaml"), "--config", "-c"),
    agent_id: Optional[str] = typer.Option(None, "--agent", "-a", help="Target agent ID"),
    all_agents: bool = typer.Option(False, "--all", help="Push to all agents"),
    version: Optional[str] = typer.Option(None, "--version", "-v", help="Skill version to push"),
    force: bool = typer.Option(False, "--force", help="Push even if version is pinned"),
):
    """Push a skill to one or more agents."""
    from ..runtime.watcher import SkillsWatcher

    fleet = _load_fleet(config)
    watcher = SkillsWatcher(fleet)

    targets = []
    if all_agents:
        targets = [a.id for a in fleet.agents]
    elif agent_id:
        targets = [agent_id]
    else:
        console.print("[red]Error:[/red] specify --agent <id> or --all")
        raise typer.Exit(1)

    for tid in targets:
        watcher.push_skill(tid, skill_name, version)


@push_app.command("plugin")
def push_plugin(
    plugin_name: str = typer.Argument(..., help="Plugin name to push"),
    config: Path = typer.Option(Path("fleet.yaml"), "--config", "-c"),
    agent_id: Optional[str] = typer.Option(None, "--agent", "-a", help="Target agent ID"),
    all_agents: bool = typer.Option(False, "--all", help="Push to all agents"),
):
    """Push a plugin to one or more agents (updates fleet config)."""
    fleet = _load_fleet(config)

    targets = []
    if all_agents:
        targets = fleet.agents
    elif agent_id:
        agent = fleet.get_agent(agent_id)
        if not agent:
            console.print(f"[red]Agent {agent_id} not found[/red]")
            raise typer.Exit(1)
        targets = [agent]
    else:
        console.print("[red]Error:[/red] specify --agent <id> or --all")
        raise typer.Exit(1)

    for agent in targets:
        if plugin_name not in agent.plugins:
            agent.plugins.append(plugin_name)
            console.print(f"[green]✓[/green] Added plugin [bold]{plugin_name}[/bold] to {agent.emoji} {agent.name}")
        else:
            console.print(f"[dim]Plugin {plugin_name} already in {agent.name}[/dim]")

    console.print("\n[dim]Run [bold]fleetmind render[/bold] to update openclaw.json[/dim]")


