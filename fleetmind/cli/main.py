@agent_app.command("list")
def agent_list(
    config: Path = typer.Option(Path("fleet.yaml"), "--config", "-c"),
):
    """List all agents in the fleet."""
    fleet = _load_fleet(config)

    for agent in fleet.agents:
        role = "orchestrator" if agent.orchestrator else "specialist"
        console.print(f"  {agent.emoji} [bold]{agent.name}[/bold] ({agent.id}) — {role}")


@agent_app.command("info")
def agent_info(
    agent_id: str = typer.Argument(..., help="Agent ID"),
    config: Path = typer.Option(Path("fleet.yaml"), "--config", "-c"),
):
    """Show details for a specific agent."""
    fleet = _load_fleet(config)
    agent = fleet.get_agent(agent_id)

    if not agent:
        console.print(f"[red]Agent '{agent_id}' not found.[/red]")
        console.print(f"Available: {', '.join(a.id for a in fleet.agents)}")
        raise typer.Exit(1)

    workspace = Path(fleet.defaults.workspace_base) / f"workspace-{agent.id}"
    console.print(Panel(
        f"[bold]{agent.emoji} {agent.name}[/bold] ({agent.id})\n"
        f"Role: {'orchestrator' if agent.orchestrator else 'specialist'}\n"
        f"Model: {agent.model or fleet.defaults.model}\n"
        f"Description: {agent.description}\n\n"
        f"Slack account: {agent.slack.account_id}\n"
        f"Skills: {', '.join(s.name + ('@' + s.version if s.version else '') for s in agent.skills) or '—'}\n"
        f"Plugins: {', '.join(agent.plugins) or '—'}\n"
        f"Can send to: {', '.join(agent.agent_to_agent.can_send_to) or '—'}\n\n"
        f"Workspace: {workspace} ({'exists' if workspace.exists() else 'not provisioned'})",
        title=f"Agent: {agent.id}",
    ))


# ── secrets subcommands ───────────────────────────────────────────────────────

@secrets_app.command("set")
def secrets_set(
    key: str = typer.Argument(..., help="Secret key"),
    value: str = typer.Argument(..., help="Secret value"),
):
    """Store a secret in the fleet's local secret store."""
    secrets = _load_secrets()
    secrets[key] = value
    _save_secrets(secrets)
    # Also set in current environment for immediate use
    os.environ[key] = value
    console.print(f"[green]✓[/green] Secret [bold]{key}[/bold] stored.")


@secrets_app.command("list")
def secrets_list():
    """List stored secret keys (values are never shown)."""
    secrets = _load_secrets()
    if not secrets:
        console.print("[dim]No secrets stored.[/dim]")
        return
    console.print("[bold]Stored secrets:[/bold]")
    for key in sorted(secrets):
        console.print(f"  [cyan]{key}[/cyan] = [dim]***[/dim]")


@secrets_app.command("export")
def secrets_export():
    """Export secrets as shell export statements."""
    secrets = _load_secrets()
    for key, value in secrets.items():
        print(f"export {key}={value!r}")


def main():
    # Load secrets into env before running any command
    try:
        for key, value in _load_secrets().items():
            if key not in os.environ:
                os.environ[key] = value
    except Exception:
        pass
    app()
